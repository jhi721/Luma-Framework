// ---- The passes this mod acts on or logs, keyed on the pixel shader.
enum class Pass : uint8_t
{
   None,
   Uber,        // SFX uber post, any of its 64 cooked perms (see kPasses)
   UberHalfRes, // motion blur into the half-res buffer
   Fxaa,        // FXAA 3 console (reads luma from the uber's alpha) or one of the PC presets FXAA0..5
   Video,       // Bink YUV->RGB, byte-identical to ME2 2010 and BL2/TPS
   // Vanilla bloom, quarter res (962x542 at 4K). Bright pass on both sources: tap * saturate((max(rgb) - cb4[8].y) * 0.5).
   DofBloomGather,  // full-res DoF perms: DoF blur + bloom in one target, x0.25
   BloomDownsample, // half-res perms: bloom only, /16, alpha 0
   BloomFilter,     // separable 14-tap blur (weights cb4[11..24]), H then V; also blurs the gather's DoF
   GammaCorrection, // UE3 FGammaCorrectionPixelShader, after a gamma-less uber
};
static constexpr bool IsBloomSource(Pass pass)
{
   return pass == Pass::DofBloomGather || pass == Pass::BloomDownsample;
}

