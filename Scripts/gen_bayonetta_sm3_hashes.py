"""Generates Source/Games/Bayonetta/ShaderHashes.h: the CRC32 (Core's D3D9 module "Crc32") of the raw SM3 bytecode, as the game's
CreatePixelShader gets it, of the named Bayonetta pixel shader sets the native D3D9 mod looks for.

Usage: python Scripts/gen_bayonetta_sm3_hashes.py DUMP_DIR
  DUMP_DIR: the game's shader.dat extracted with one "<name>.ps3" bytecode file per pixel shader in DUMP_DIR/in_ps
"""
import re
import sys
import zlib
from pathlib import Path

if len(sys.argv) != 2:
    sys.exit(__doc__)
ps = {p.stem: zlib.crc32(p.read_bytes()) for p in sorted((Path(sys.argv[1]) / 'in_ps').glob('*.ps3'))}


def named(pattern):
    names = sorted(n for n in ps if re.fullmatch(pattern, n))
    if not names:
        sys.exit('no pixel shader matches ' + pattern)
    return names


sets = [
    ('kScenePostPs', named(r'modelshaderblur(cm\w+|srcweight|weight)?|filter08(_[0-4])?|filter00|filter04'),
     'the scene\'s first post pass, which ends a motion vector frame: modelshaderblur, blurcm*, blursrcweight, blurweight, filter08 + '
     '_0.._4 (DoF), filter00 / filter04 (grade)'),
    ('kRefractionPs', named(r'espshadershimmer\w*|espshaderwaterwave'),
     'screen space refraction (espshadershimmer*, espshaderwaterwave): jittered, no motion vectors'),
    ('kSsaoPs', named(r'filtershaderssao'), 'filtershaderssao: its s2 is the R32F depth prepass (SMAA predication, XeGTAO)'),
    ('kPixelKernelPs', named(r'filtershadow_[1-3]|filtershaderssao'),
     'kernels stepping in pixels of their target by c194 (Fix High Resolution Effects): filtershadow_1..3, filtershaderssao'),
    ('kBloomSourcePs', named(r'filter05'), 'filter05: the scene into the bloom target, then each level\'s threshold and halving'),
    ('kBloomBlurPs', named(r'filter0[12]'), 'filter01 / filter02: each bloom level\'s blur'),
    ('kBloomCopyPs', named(r'filtershadercopytex'), 'filtershadercopytex: the bloom level copies and composite'),
    ('kHandoffPs', named(r'filtershadercopytex|espshadermultimoveparticle(billbord|cb|cylinder)?|espshadermultiparticle(3d)?'),
     'draws into the back buffer whose s0 is the hand-off source (ResetRender): filtershadercopytex and the '
     'espshadermulti*particle* sharing one bytecode'),
    ('kVideoPs', named(r'smp_video_yuv_rgb_conv_shader_vs'), 'the Sofdec movies\' Y\'CbCr to R\'G\'B\' (kept under Hide UI)'),
    ('kVelocityPs', named(r'modelshaderblursrcweight'),
     'the skinned motion blur velocity into an A8R8G8B8 target the upgrade makes fp16: clamped as UNORM8'),
]

out = ['// Generated by Scripts/gen_bayonetta_sm3_hashes.py from the game\'s SM3 pixel shaders: CRC32 of the raw bytecode. Do not edit.',
       '#pragma once', '', '#include <cstdint>', '']
for name, names, doc in sets:
    out.append('// %s: %s' % (name, doc))
    for n in names:
        out.append('//   %-40s 0x%08X' % (n, ps[n]))
    out.append('inline constexpr uint32_t %s[] = {%s};' % (name, ', '.join('0x%08X' % ps[n] for n in names)))
    out.append('')
(Path(__file__).parent.parent / 'Source' / 'Games' / 'Bayonetta' / 'ShaderHashes.h').write_text('\n'.join(out), encoding='utf8')
print({n: len(v) for n, v, _ in sets})
